import { createRequire } from 'node:module'
const { chromium } = createRequire(import.meta.url)('playwright')
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const p = await b.newPage({ viewport: { width: 640, height: 360 } })
const errs = []
p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text() + ' @ ' + m.location().url) })
p.on('pageerror', (e) => errs.push('pageerror: ' + e.message))
const ok = (name, cond) => console.log((cond ? 'PASS ' : 'FAIL ') + name)
const until = (expr, ms = 20000) => p.waitForFunction(`(() => { const G = __game; return ${expr} })()`, null, { timeout: ms }).then(() => true, () => false)
await p.goto('http://localhost:8933/turf-trouble/')
await p.waitForTimeout(1500)
ok('no SDK present', await p.evaluate(() => typeof window.TwoWeb === 'undefined'))
// traffic keeps moving behind the menu
await p.waitForTimeout(20000)
const tr = await p.evaluate(() => __game.cars.filter((c) => c.kind === 'traffic').map((c) => +c.speed.toFixed(1)))
ok('traffic flowing ' + JSON.stringify(tr), tr.filter((s) => s > 2).length >= tr.length * 0.6)
await p.click('#btn-new'); await p.waitForTimeout(800); await p.keyboard.press('KeyX')
await until(`G.state.mode === 'play'`); await p.waitForTimeout(500)
await p.evaluate(() => { const s = __game.poi.hideout.save; __game.teleport(s[0], s[1]) })
ok('mission 1', await until(`G.state.mission === 1`))
await p.click('#modal-buttons button')
ok('continue works with no ad', await until(`document.getElementById('modal').hidden && !G.state.adPaused`, 3000))
await p.evaluate(() => __game.busted())
await p.locator('#modal-buttons button').nth(1).click(); await p.waitForTimeout(300)
ok('rewarded ad "not shown" gives nothing', (await p.locator('#modal-buttons button').nth(1).textContent()).includes('NO AD AVAILABLE'))
const m = await p.evaluate(() => __game.state.money)
await p.locator('#modal-buttons button').nth(0).click()
ok('fine applies', await until(`document.getElementById('modal').hidden && G.state.money === ${m - 200}`, 3000))
// a real chase: police have to find the player through the streets
await p.evaluate(() => { __game.teleport(0, 0); __game.offence(90) })
ok('police car spawned and closing in', await until(`G.cars.some((c) => c.kind === 'police' && c.chasing && Math.hypot(c.x - G.player.x, c.z - G.player.z) < 12)`, 120000))
console.log(errs.length ? 'console errors:\n' + errs.join('\n') : 'no console errors')
await b.close()
