import { createRequire } from 'node:module'
const { chromium, devices } = createRequire(import.meta.url)('playwright')
const out = process.argv[2]
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, deviceScaleFactor: 1 })
const p = await ctx.newPage()
const errs = []
p.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.type() + ': ' + m.text()) })
p.on('pageerror', (e) => errs.push('pageerror: ' + e.message))
const ok = (name, cond) => console.log((cond ? 'PASS ' : 'FAIL ') + name)
const until = (expr, ms = 20000) => p.waitForFunction(`(() => { const G = __game; return ${expr} })()`, null, { timeout: ms }).then(() => true, () => false)
const cdp = await ctx.newCDPSession(p)
const touch = (type, pts) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: pts.map(([x, y], id) => ({ x, y, id })) })
await p.goto('http://localhost:8932/games/turf-trouble/')
await p.waitForTimeout(1500)
await p.evaluate(() => { window.__adMs = 300 })
await p.screenshot({ path: out + '/ph-menu.png' })
await p.tap('#btn-new'); await p.waitForTimeout(900)
await p.screenshot({ path: out + '/ph-intro.png' })
await p.touchscreen.tap(200, 400)
ok('tap skips intro', await until(`G.state.mode === 'play'`))
const x0 = await p.evaluate(() => [__game.player.x, __game.player.z])
await touch('touchStart', [[100, 600]]); await touch('touchMove', [[100, 540]]); await p.waitForTimeout(1500)
await p.screenshot({ path: out + '/ph-walk.png' })
// second finger looks around while the first keeps walking
const yaw0 = await p.evaluate(() => __game.cam.yaw)
await touch('touchStart', [[100, 540], [300, 400]]); await touch('touchMove', [[100, 540], [240, 400]]); await p.waitForTimeout(300)
await touch('touchEnd', [])
const x1 = await p.evaluate(() => [__game.player.x, __game.player.z, __game.cam.yaw])
ok('joystick walks', Math.hypot(x1[0] - x0[0], x1[1] - x0[1]) > 1.5)
ok('second finger looks', Math.abs(x1[2] - yaw0) > 0.1)
// drive with touch
await p.evaluate(() => { const G = __game, c = G.cars.find(c => c.kind === 'crew' && Math.hypot(c.x - G.player.x, c.z - G.player.z) < 30); G.teleport(c.x, c.z - 2.6) })
await p.waitForTimeout(500)
ok('DRIVE button shown', await p.locator('#t-act').isVisible())
await p.tap('#t-act')
ok('entered car by touch', await until(`!!G.player.car`, 4000))
await touch('touchStart', [[100, 600]]); await touch('touchMove', [[100, 550]])
ok('touch accelerates', await until(`G.player.car.speed > 8`, 15000))
await p.screenshot({ path: out + '/ph-drive.png' })
await touch('touchEnd', [])
await p.evaluate(() => { __game.player.car.speed = 0 })
await p.tap('#t-act')
ok('exit by touch', await until(`!G.player.car`, 4000))
// get the popper and fire by touch
await p.evaluate(() => { const G = __game; G.state.mission = 2; const s = G.poi.hideout.stands[0]; G.teleport(s[0], s[1] + 1) })
await until(`G.state.mission === 3`); await p.waitForTimeout(300)
await p.screenshot({ path: out + '/ph-modal.png' })
await p.tap('#modal-buttons button'); await until(`document.getElementById('modal').hidden`, 5000)
ok('FIRE button shown', await p.locator('#t-fire').isVisible())
const b0 = await p.locator('#t-fire').boundingBox()
await touch('touchStart', [[b0.x + 40, b0.y + 40]]); await p.waitForTimeout(700); await touch('touchEnd', [])
ok('touch fire uses ammo', await until(`G.player.mag < 12`, 3000))
await p.screenshot({ path: out + '/ph-armed.png' })
// every touch button stays out of the outer 40 px
const boxes = await p.evaluate(() => [...document.querySelectorAll('.tb:not([hidden]), .icon, #minimap, #money')].map((e) => { const r = e.getBoundingClientRect(); return [e.id, Math.round(r.left), Math.round(r.top), Math.round(innerWidth - r.right), Math.round(innerHeight - r.bottom)] }))
ok('controls inside the 40 px safe area ' + JSON.stringify(boxes), boxes.every((b) => b.slice(1).every((v) => v >= 40)))
await p.tap('#btn-pause'); await p.waitForTimeout(300)
await p.screenshot({ path: out + '/ph-pause.png' })
await p.tap('#modal-buttons button')
await p.setViewportSize({ width: 844, height: 390 }); await p.waitForTimeout(700)
await p.screenshot({ path: out + '/ph-land.png' })
await p.tap('#minimap'); await p.waitForTimeout(300)
await p.screenshot({ path: out + '/ph-land-map.png' })
await p.tap('#btn-map-close')
const info = await p.evaluate(() => { const i = __game.renderer.info; return { calls: i.render.calls, tris: i.render.triangles } })
console.log('render', JSON.stringify(info))
console.log(errs.length ? errs.join('\n') : 'no console errors')
await b.close()
